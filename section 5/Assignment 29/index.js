//number classification//

let number = 150;

if (number > 0) {
    console.log("Positive");
} else if (number < 0) {
    console.log("Negative");
} else {
    console.log("Zero");
}

if (number % 2 === 0) {
    console.log("Even");
} else {
    console.log("Odd");
}

if (number > 100) {
    console.log("Greater than 100");
} else if (number < 100) {
    console.log("Less than 100");
} else {
    console.log("Equal to 100");
}